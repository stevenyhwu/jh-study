/* ===== 數學 4-1 因式分解法解一元二次方程式 ===== */
(function () {
  'use strict';
  const U = Unit4, h = U.h, K = MK, M = K.M, X2 = K.X2;
  const has = (S, a, b) => S.found.indexOf(a) >= 0 && S.found.indexOf(b) >= 0;
  const linePic = (host, pts) => { const l = K.lineSvg(8, pts); return U.svg(host, l.vb, l.inner, '數線上的根', 'u4-pic'); };

  function guess(p, api) {
    U.guess(p, api, [
      { q: '兩個數乘起來是 <b>0</b>。關於這兩個數，哪一句一定對？', options: [{ t: '至少有一個是 0', ok: true }, { t: '兩個都是 0' }, { t: '不一定，要看情況' }],
        reveal: '<b>至少有一個是 0</b>。像 0 × 5 ＝ 0、(−3) × 0 ＝ 0。只要有一個是 0，乘起來就是 0。這句話是今天的主角。' },
      { q: `${M(X2 + ' ＝ 4x')}，x 可以是哪些數？`, options: [{ t: '只有 4' }, { t: '0 和 4', ok: true }, { t: '只有 0' }],
        reveal: '<b>0 和 4</b> 都可以：0² ＝ 4 × 0 ✔，4² ＝ 4 × 4 ✔。一元二次方程式通常有<b>兩個解</b>，只找到一個是不夠的。' }
    ]);
  }

  function play(p, api) {
    let S;
    const card = h('<div class="card"></div>'); p.appendChild(card);
    const tk = U.tasks(p, api, [
      { text: `拉 x，找出<b>所有</b>讓 ${M('(x − 2)(x + 3) ＝ 0')} 的 x。（有兩個）`, setup() { S.setEq(-2, 3); }, check: () => has(S, 2, -3),
        qs: () => [{ q: 'x ＝ 2 和 x ＝ −3 為什麼剛好是答案？', options: [{ t: 'x ＝ 2 讓 (x − 2) 變 0；x ＝ −3 讓 (x + 3) 變 0', ok: true, why: '只要其中一個括號是 0，乘起來就是 0。' }, { t: '湊巧而已', why: '看讀數：x ＝ 2 時，哪個括號是 0？' }] }],
        found: `${M('A × B ＝ 0')} → <b>A ＝ 0 或 B ＝ 0</b>。每個括號各給一個解，這些解叫做方程式的<b>根</b>。` },
      { text: `這次沒有括號：${M(X2 + ' − 5x + 6 ＝ 0')}。先想它怎麼因式分解，再找出兩個根。`, setup() { S.setEq(-2, -3, X2 + ' − 5x + 6 ＝ 0'); }, check: () => has(S, 2, 3),
        qs: () => [{ q: '不用一個一個試，怎麼直接算出 2 和 3？', options: [{ t: '因式分解成 (x − 2)(x − 3) ＝ 0，再讓每個括號 ＝ 0', ok: true, why: 'x − 2 ＝ 0 → x ＝ 2；x − 3 ＝ 0 → x ＝ 3。' }, { t: '把 6 開根號', why: '√6 不是整數，代進去也不會是 0。' }] }],
        found: '<b>因式分解法</b>：先分解成兩個括號相乘 ＝ 0，再讓每個括號 ＝ 0。' },
      { text: `最後：${M(X2 + ' ＝ 4x')}。找出兩個根。`, setup() { S.setEq(0, -4, X2 + ' ＝ 4x'); }, check: () => has(S, 0, 4),
        qs: () => [{ q: '如果兩邊「同除以 x」，會得到 x ＝ 4。這樣做哪裡有問題？', options: [{ t: '少了 x ＝ 0 這個根', ok: true, why: 'x 可能是 0，不能拿來除。正確做法：移項 x² − 4x ＝ 0 → x(x − 4) ＝ 0 → x ＝ 0 或 4。' }, { t: '沒問題', why: '看數線上的綠點：有幾個根？' }] }],
        found: '<b>不要兩邊同除以 x</b>。把東西全部移到左邊，讓右邊 ＝ 0，再提公因式。' }
    ]);
    S = K.rootSim(card, () => tk.check());
    card.appendChild(tk.slot); p.insertBefore(p.querySelector('.u4-task'), card); tk.start();
  }

  function know(p, api) {
    p.appendChild(h('<p class="muted">把剛剛玩到的，收成 4 句話。</p>'));
    K.table(U.card(p, '① 根（解）：代進去會成立的數', `<p>${M(X2 + ' − 5x + 6 ＝ 0')} 的根是 2 和 3：代進去左邊剛好是 0。</p>`), ['x', 'x² − 5x + 6'], [['1', '2'], ['<b>2</b>', '<b>0 ✔</b>'], ['<b>3</b>', '<b>0 ✔</b>'], ['4', '2']], 240);
    linePic(U.card(p, '② 乘起來是 0 → 至少一個是 0', `<p>${M('(x − 2)(x + 3) ＝ 0')}<br>→ x − 2 ＝ 0 或 x + 3 ＝ 0<br>→ <b>x ＝ 2 或 x ＝ −3</b></p>`), [2, -3]);
    K.table(U.card(p, '③ 三個步驟', `<p>例：${M(X2 + ' + 2x ＝ 15')}</p>`), ['步驟', '做什麼', '例子'], [['1', '全部移到左邊，右邊 ＝ 0', 'x² + 2x − 15 ＝ 0'], ['2', '左邊因式分解', '(x + 5)(x − 3) ＝ 0'], ['3', '每個括號 ＝ 0', 'x ＝ −5 或 x ＝ 3']], 420);
    K.table(U.card(p, '④ 兩個陷阱', '<p>右邊<b>一定要是 0</b> 才能拆；<b>不能</b>兩邊同除以 x。</p>'), ['錯的做法', '為什麼錯', '正確'], [['x² ＝ 4x → x ＝ 4', '少了 x ＝ 0', 'x(x − 4) ＝ 0'], ['(x − 1)(x − 2) ＝ 6 → x ＝ 1 或 2', '右邊不是 0', '先乘開、移項']], 420);
    const c = h('<div class="card"><h3>✏️ 檢查一下</h3></div>'); p.appendChild(c);
    U.choice(c, { q: `${M('(x + 4)(x − 1) ＝ 0')} 的解是？`, hint: 'x + 4 ＝ 0 時 x 是多少？',
      options: [{ t: 'x ＝ −4 或 x ＝ 1', ok: true, why: 'x + 4 ＝ 0 → x ＝ −4；x − 1 ＝ 0 → x ＝ 1。' }, { t: 'x ＝ 4 或 x ＝ −1', why: '符號反了：x + 4 ＝ 0 時，x 是 −4。' }, { t: 'x ＝ −4', why: '還有另一個括號。' }], onDone() { api.done(); } });
  }

  function exam(p, api) {
    U.exam(p, api, {
      intro: '這兩題是照會考題的樣子改寫的，數字比較好算。答錯可以再選。',
      qs: [
        { src: '改寫自 107 年會考第 8 題', q: `若一元二次方程式 ${M(X2 + ' − 3x − 10 ＝ 0')} 的兩根為 a、b，且 a ＞ b，則 2a + b 之值為何？`, hint: '先因式分解：乘起來 −10、加起來 −3。',
          options: [{ t: '3', why: '3 是 a ＋ b；題目問 2a ＋ b。' }, { t: '1', why: 'a 是比較大的根（5），不是 −2。' }, { t: '8', ok: true, why: '(x − 5)(x + 2) ＝ 0，a ＝ 5、b ＝ −2，2a + b ＝ 10 − 2 ＝ 8。' }, { t: '12', why: 'b 是 −2，不是 2。' }] },
        { src: '改寫自 115 年會考第 9 題', q: `已知一元二次方程式 ${M('x(x + 3) − 2(x + 3) ＝ 0')} 的兩根為 a、b，且 a ＞ b，求 a − b 之值為何？`, hint: '兩項都有 (x + 3)，先提出來。',
          options: [{ t: '−1', why: '−1 是 a ＋ b；題目問 a − b。' }, { t: '5', ok: true, why: '(x + 3)(x − 2) ＝ 0，a ＝ 2、b ＝ −3，a − b ＝ 2 − (−3) ＝ 5。' }, { t: '−5', why: 'a 是比較大的根（2）。' }, { t: '1', why: 'b 是 −3，減負數等於加。' }] }
      ]
    });
  }

  function real(p, api) {
    U.real(p, api, [
      { stars: 1, src: K.SIM, q: `一元二次方程式 ${M(X2 + ' + 5x ＝ 0')} 的解為何？`,
        options: [{ t: 'x ＝ 5', why: '代進去：25 ＋ 25 ＝ 50，不是 0。' }, { t: 'x ＝ −5', why: '−5 是其中一個，還有一個。' }, { t: 'x ＝ 0 或 x ＝ 5', why: 'x + 5 ＝ 0 時，x 是 −5。' }, { t: 'x ＝ 0 或 x ＝ −5', ok: true, why: 'x(x + 5) ＝ 0 → x ＝ 0 或 x ＝ −5。' }],
        explain: '<p>提公因式：x² + 5x ＝ x(x + 5) ＝ 0。<br>x ＝ 0 或 x + 5 ＝ 0，所以 x ＝ 0 或 x ＝ −5。答案 (D)。</p>',
        steps: [
          { q: `${M(X2 + ' + 5x')} 因式分解是？`, options: [{ t: 'x(x + 5)', ok: true, why: '兩項都有 x。' }, { t: '(x + 5)(x − 5)', why: '那是 x² − 25。' }] },
          { q: `${M('x(x + 5) ＝ 0')}，所以？`, options: [{ t: 'x ＝ 0 或 x ＝ −5', ok: true, why: '前面那個 x 自己也是一個「括號」。' }, { t: '只有 x ＝ −5', why: '前面的 x 等於 0 時，乘起來也是 0。' }] }
        ] },
      { stars: 2, src: '115 年會考 第 9 題', q: `已知一元二次方程式 ${M('2x(x + 7) − 10(x + 7) ＝ 0')} 的兩根為 a、b，且 a ＞ b，求 a + 2b 之值為何？`,
        options: [{ t: '−13', why: '再檢查兩個根：x + 7 ＝ 0 和 2x − 10 ＝ 0。' }, { t: '−9', ok: true, why: 'a ＝ 5、b ＝ −7，a + 2b ＝ 5 − 14 ＝ −9。' }, { t: '−4', why: '再檢查：a 是 5、b 是 −7，b 要乘 2。' }, { t: '−3', why: '根的符號反了：x + 7 ＝ 0 → x ＝ −7；2x − 10 ＝ 0 → x ＝ 5。' }],
        explain: '<p>兩項都有 (x + 7)，提出來：(x + 7)(2x − 10) ＝ 0。<br>x + 7 ＝ 0 → x ＝ −7；2x − 10 ＝ 0 → x ＝ 5。<br>a ＞ b，所以 a ＝ 5、b ＝ −7，a + 2b ＝ 5 ＋ 2 × (−7) ＝ −9。答案 (B)。<br>💡 不要乘開！乘開會變成 2x² + 4x − 70 ＝ 0，反而更難。</p>',
        steps: [
          { q: '兩項 2x(x + 7) 和 −10(x + 7) 都有 (x + 7)。提出來變成？', options: [{ t: '(x + 7)(2x − 10) ＝ 0', ok: true, why: '提公因式（3-1 學的）。' }, { t: '(x + 7)(2x + 10) ＝ 0', why: '第二項前面是減號。' }] },
          { q: '每個括號 ＝ 0，兩個根是？', options: [{ t: 'x ＝ −7 或 x ＝ 5', ok: true, why: 'x + 7 ＝ 0 → −7；2x − 10 ＝ 0 → 2x ＝ 10 → 5。' }, { t: 'x ＝ 7 或 x ＝ −5', why: '符號反了。' }, { t: 'x ＝ −7 或 x ＝ 10', why: '2x ＝ 10，還要除以 2。' }] },
          { num: true, signed: true, q: 'a 是比較大的根。a ＝ 5、b ＝ −7，a + 2b ＝ ？', pre: 'a + 2b ＝', answer: -9, diag: [{ v: 3, msg: 'a 是比較大的那個（5），b 是 −7。' }, { v: 19, msg: 'b 是 −7：5 ＋ 2 × (−7)。' }] }
        ] },
      { stars: 3, src: K.SIM, q: `已知 x ＝ 2 是一元二次方程式 ${M(X2 + ' + kx − 6 ＝ 0')} 的一根，則此方程式的另一根為何？`,
        options: [{ t: '−3', ok: true, why: 'k ＝ 1，x² + x − 6 ＝ (x + 3)(x − 2) ＝ 0，另一根是 −3。' }, { t: '3', why: 'x + 3 ＝ 0 時，x 是 −3。' }, { t: '−1', why: '先把 x ＝ 2 代進去求 k。' }, { t: '1', why: '1 是 k 的值，不是另一根。' }],
        explain: '<p>「x ＝ 2 是根」＝ 把 2 代進去會成立：4 ＋ 2k − 6 ＝ 0 → k ＝ 1。<br>方程式是 x² + x − 6 ＝ 0 → (x + 3)(x − 2) ＝ 0 → x ＝ −3 或 2。<br>另一根是 −3。答案 (A)。</p>',
        steps: [
          { num: true, signed: true, q: '把 x ＝ 2 代進去：4 ＋ 2k − 6 ＝ 0。k ＝ ？', pre: 'k ＝', answer: 1, hint: '2k − 2 ＝ 0。' },
          { q: `${M(X2 + ' + x − 6')} 因式分解是？`, options: [{ t: '(x + 3)(x − 2)', ok: true, why: '3 × (−2) ＝ −6，3 ＋ (−2) ＝ 1 ✔' }, { t: '(x − 3)(x + 2)', why: '中間會是 −x。' }] },
          { q: `${M('(x + 3)(x − 2) ＝ 0')}，除了 2 以外的另一根是？`, options: [{ t: '−3', ok: true, why: 'x + 3 ＝ 0 → x ＝ −3。' }, { t: '3', why: 'x + 3 ＝ 0 時 x 是負的。' }] }
        ] }
    ]);
  }

  K.run('4-1', ['先猜猜看：乘起來是 0', '動手玩：代 x 找根', '收成 4 句話', '會考題改寫版', '實戰：會考原題與模擬題'], { guess, play, know, exam, real });
})();
