/* ===== 數學 4-2a 配方法 ===== */
(function () {
  'use strict';
  const U = Unit4, h = U.h, K = MK, M = K.M, X2 = K.X2, R = K.sqrt;
  const sq = s => `${s}<sup>2</sup>`;
  const linePic = (host, pts) => { const l = K.lineSvg(8, pts); return U.svg(host, l.vb, l.inner, '數線上的根', 'u4-pic'); };

  function guess(p, api) {
    U.guess(p, api, [
      { q: `${M(X2 + ' ＝ 9')}，x 可以是哪些數？`, options: [{ t: '只有 3' }, { t: '3 和 −3', ok: true }, { t: '4.5' }],
        reveal: '<b>3 和 −3</b>：(−3)² 也是 9。寫成 x ＝ ±3。平方等於一個正數，一定有<b>正負兩個</b>答案。' },
      { q: `${M(X2 + ' + 6x')} 再加上多少，就會變成一個完全平方 ${M(sq('(x + □)'))}？`, options: [{ t: '6' }, { t: '9', ok: true }, { t: '36' }],
        reveal: `加 <b>9</b>：${M(X2 + ' + 6x + 9 ＝ ' + sq('(x + 3)'))}。這個「補一塊變正方形」的動作叫<b>配方</b>，下一步自己補補看。` }
    ]);
  }

  function play(p, api) {
    let S;
    const card = h('<div class="card"></div>'); p.appendChild(card);
    const tk = U.tasks(p, api, [
      { text: `${M(X2 + ' + 6x')}：拉「補上的數」，把右下角的缺口剛好補滿。`, setup() { S.setB(6); }, check: () => S.full(6),
        qs: () => [{ q: '缺口的邊長是 3。這個 3 跟 6x 的 6 有什麼關係？', options: [{ t: '3 是 6 的一半', ok: true, why: '6x 被分成兩條 3x，一條在右邊、一條在下面，所以缺口是 3 × 3。' }, { t: '3 是 6 開根號', why: '看圖：兩條綠色長條各是 3x，加起來 6x。' }] }],
        found: 'x 項分成<b>兩半</b>，缺口是「一半 × 一半」。' },
      { text: `按上面的 <b>10x</b>，再補滿一次。`, setup() { S.setB(6); }, check: () => S.full(10),
        qs: () => [{ num: true, q: `10x → 一半是 5 → 補 25。那 ${M(X2 + ' + 8x')} 要補多少？`, pre: '補', answer: 16, hint: '8 的一半是 4，4 × 4。', diag: [{ v: 4, msg: '4 是一半，還要平方。' }, { v: 64, msg: '要先取一半再平方：4²。' }], why: `${M(X2 + ' + 8x + 16 ＝ ' + sq('(x + 4)'))}` }],
        found: `<b>配方</b>：補上「x 項係數<b>一半的平方</b>」，就變成完全平方。` },
      { text: `用配方來解方程式：${M(X2 + ' + 6x ＝ 7')}。`, quiet: true, check: () => true,
        qs: () => [
          { q: '左邊要補 9 才是完全平方。等號要平衡，所以……', options: [{ t: `兩邊都加 9：${M(sq('(x + 3)') + ' ＝ 16')}`, ok: true, why: '左邊 x² + 6x + 9 ＝ (x + 3)²，右邊 7 ＋ 9 ＝ 16。' }, { t: `只有左邊加 9：${M(sq('(x + 3)') + ' ＝ 7')}`, why: '只加一邊，等號就不成立了。' }] },
          { q: `${M(sq('(x + 3)') + ' ＝ 16')}，所以 x + 3 ＝ ？`, options: [{ t: '4 或 −4', ok: true, why: '平方是 16 的數有兩個：±4。' }, { t: '只有 4', why: '(−4)² 也是 16。' }, { t: '8 或 −8', why: '16 要開根號，不是除以 2。' }] },
          { q: 'x + 3 ＝ 4 或 x + 3 ＝ −4，所以 x ＝ ？', options: [{ t: '1 或 −7', ok: true, why: '代回去檢查：1 ＋ 6 ＝ 7 ✔；49 − 42 ＝ 7 ✔' }, { t: '7 或 −1', why: '是減 3：4 − 3、−4 − 3。' }] }],
        found: '配方法：<b>補一半的平方（兩邊都加）→ 寫成 (　)² ＝ 數 → 開根號取 ± → 算出 x</b>。' }
    ]);
    S = K.sqSim(card, () => tk.check(), { bs: [6, 10, 4] });
    card.appendChild(tk.slot); p.insertBefore(p.querySelector('.u4-task'), card); tk.start();
  }

  function know(p, api) {
    p.appendChild(h('<p class="muted">把剛剛玩到的，收成 4 句話。</p>'));
    linePic(U.card(p, '① 平方根法：開根號要取 ±', `<p>${M(sq('(x − 1)') + ' ＝ 9')} → x − 1 ＝ ±3 → <b>x ＝ 4 或 x ＝ −2</b></p><p>在數線上：從 1 出發，往左、往右各走 3。</p>`), [4, -2]);
    K.boxPic(U.card(p, '② 配方：補「一半的平方」', `<p>${M(X2 + ' + 6x')} → 6 的一半是 3 → 補 3² ＝ 9<br>${M(X2 + ' + 6x + 9 ＝ ' + sq('(x + 3)'))}</p><p>x 項是負的也一樣：${M(X2 + ' − 8x + 16 ＝ ' + sq('(x − 4)'))}</p>`), 3, 3);
    K.table(U.card(p, '③ 配方法四步', `<p>例：${M(X2 + ' + 6x − 7 ＝ 0')}</p>`), ['步驟', '做什麼', '例子'], [['1', '常數移到右邊', 'x² + 6x ＝ 7'], ['2', '兩邊加「一半的平方」', 'x² + 6x + 9 ＝ 16'], ['3', '左邊寫成平方', '(x + 3)² ＝ 16'], ['4', '開根號取 ±', 'x + 3 ＝ ±4 → x ＝ 1 或 −7']], 420);
    K.table(U.card(p, '④ 右邊開不盡也沒關係', `<p>${M(sq('(x − 2)') + ' ＝ 3')} → x − 2 ＝ ±${R(3)} → <b>x ＝ 2 ± ${R(3)}</b></p><p>答案留著根號就好。</p>`), ['(　)² ＝ k', '解'], [['k 是正的', '兩個解'], ['k ＝ 0', '一個解（重根）'], ['k 是負的', '沒有解（平方不會是負的）']], 320);
    const c = h('<div class="card"><h3>✏️ 檢查一下</h3></div>'); p.appendChild(c);
    U.numq(c, { q: `${M(X2 + ' − 10x')} 要加多少才會變成完全平方？`, pre: '加', answer: 25, hint: '−10 的一半是 −5，(−5)² ＝ ？', diag: [{ v: -25, msg: '平方一定是正的：(−5)² ＝ 25。' }, { v: 5, msg: '5 是一半，還要平方。' }, { v: 100, msg: '先取一半再平方。' }],
      why: `${M(X2 + ' − 10x + 25 ＝ ' + sq('(x − 5)'))}`, onDone() { api.done(); } });
  }

  function exam(p, api) {
    U.exam(p, api, {
      intro: '這兩題是照會考題的樣子改寫的，數字比較好算。答錯可以再選。',
      benchLabel: '想補補看？打開正方形模擬',
      bench: host => K.sqSim(host, () => {}, { bs: [6, 10, 4] }),
      qs: [
        { src: '改寫自 109 年會考第 10 題', q: `若一元二次方程式 ${M('3' + sq('(x − 1)') + ' ＝ 48')} 的解為 a、b，且 a ＞ b，則 2a + b 之值為何？`, hint: '先兩邊除以 3，再開根號（記得 ±）。',
          options: [{ t: '2', why: '2 是 a ＋ b；題目問 2a ＋ b。' }, { t: '7', ok: true, why: '(x − 1)² ＝ 16 → x − 1 ＝ ±4 → x ＝ 5 或 −3。2 × 5 ＋ (−3) ＝ 7。' }, { t: '−1', why: 'a 是比較大的那個（5）。' }, { t: '13', why: 'b 是 −3，不是 3。' }] },
        { src: '改寫自 106 年會考第 12 題', q: `一元二次方程式 ${M(X2 + ' − 6x ＝ 7')} 可表示成 ${M(sq('(x − a)') + ' ＝ 7 + b')} 的形式，其中 a、b 為整數。求 a + b 之值為何？`, hint: '−6 的一半是 −3，要補 9。',
          options: [{ t: '6', why: '(x − a)² 裡的 a 是 3（不是 −3），b 是 9。' }, { t: '12', ok: true, why: '兩邊加 9：(x − 3)² ＝ 7 ＋ 9。a ＝ 3、b ＝ 9。' }, { t: '15', why: 'a 是 6 的一半。' }, { t: '39', why: 'b 是「一半的平方」：3² ＝ 9，不是 6²。' }] }
      ]
    });
  }

  function real(p, api) {
    U.real(p, api, [
      { stars: 1, src: '109 年會考 第 10 題', q: `若一元二次方程式 ${M('5' + sq('(x − 4)') + ' ＝ 125')} 的解為 a、b，且 a ＞ b，則 2a + b 之值為何？`,
        options: [{ t: '−7', why: '再檢查兩個解：x − 4 ＝ 5 或 x − 4 ＝ −5。' }, { t: '−1', why: '−1 是 b；題目問 2a ＋ b。' }, { t: '11', why: '再檢查：a ＝ 9、b ＝ −1。' }, { t: '17', ok: true, why: 'a ＝ 9、b ＝ −1，2 × 9 ＋ (−1) ＝ 17。' }],
        explain: '<p>兩邊除以 5：(x − 4)² ＝ 25。<br>開根號：x − 4 ＝ ±5 → x ＝ 9 或 x ＝ −1。<br>a ＞ b，a ＝ 9、b ＝ −1，2a + b ＝ 18 − 1 ＝ 17。答案 (D)。</p>',
        steps: [
          { num: true, q: `兩邊同除以 5：${M(sq('(x − 4)') + ' ＝ ？')}`, pre: '＝', answer: 25 },
          { q: `${M(sq('(x − 4)') + ' ＝ 25')}，所以 x − 4 ＝ ？`, options: [{ t: '5 或 −5', ok: true, why: '開根號取 ±。' }, { t: '只有 5', why: '(−5)² 也是 25。' }] },
          { q: '所以兩個解是？', options: [{ t: '9 和 −1', ok: true, why: '5 ＋ 4 ＝ 9；−5 ＋ 4 ＝ −1。' }, { t: '1 和 −9', why: '是加 4：x ＝ 4 ± 5。' }] },
          { num: true, signed: true, q: 'a ＝ 9、b ＝ −1，2a + b ＝ ？', pre: '2a + b ＝', answer: 17, diag: [{ v: 7, msg: 'a 是比較大的那個（9）。' }, { v: 19, msg: 'b 是 −1。' }] }
        ] },
      { stars: 2, src: '106 年會考 第 12 題', q: `一元二次方程式 ${M(X2 + ' − 8x ＝ 48')} 可表示成 ${M(sq('(x − a)') + ' ＝ 48 + b')} 的形式，其中 a、b 為整數。求 a + b 之值為何？`,
        options: [{ t: '20', ok: true, why: '(x − 4)² ＝ 48 ＋ 16，a ＝ 4、b ＝ 16。' }, { t: '12', why: '(x − a)² ＝ (x − 4)²，所以 a ＝ 4（不是 −4）。' }, { t: '−12', why: 'b 是補上的 16，是正的。' }, { t: '−20', why: 'a、b 都是正的：a ＝ 4、b ＝ 16。' }],
        explain: '<p>−8 的一半是 −4，(−4)² ＝ 16。兩邊加 16：<br>x² − 8x + 16 ＝ 48 ＋ 16 → (x − 4)² ＝ 48 ＋ 16。<br>對照 (x − a)² ＝ 48 ＋ b：a ＝ 4、b ＝ 16，a + b ＝ 20。答案 (A)。</p>',
        steps: [
          { num: true, q: `${M(X2 + ' − 8x')} 要補多少才是完全平方？`, pre: '補', answer: 16, hint: '−8 的一半是 −4，再平方。', diag: [{ v: 64, msg: '先取一半再平方。' }, { v: 4, msg: '4 是一半，還要平方。' }] },
          { q: `兩邊都加 16：${M(X2 + ' − 8x + 16 ＝ 48 + 16')}。左邊寫成平方是？`, options: [{ t: sq('(x − 4)'), ok: true, why: '對照 (x − a)²：a ＝ 4。右邊 48 ＋ 16：b ＝ 16。' }, { t: sq('(x + 4)'), why: '中間是 −8x，括號裡是減。' }, { t: sq('(x − 8)'), why: '括號裡是「一半」。' }] },
          { num: true, q: 'a ＝ 4、b ＝ 16，a + b ＝ ？', pre: 'a + b ＝', answer: 20 }
        ] },
      { stars: 3, src: '111 年會考 第 10 題', q: `已知一元二次方程式 ${M(sq('(x − 2)') + ' ＝ 3')} 的兩根為 a、b，且 a ＞ b，求 2a + b 之值為何？`,
        options: [{ t: '9', why: '3 要開根號：x − 2 ＝ ±√3，不是 ±3。' }, { t: '−3', why: '兩個根是 2 ＋ √3 和 2 − √3。' }, { t: `6 + ${R(3)}`, ok: true, why: `2(2 + √3) ＋ (2 − √3) ＝ 4 ＋ 2√3 ＋ 2 − √3 ＝ 6 ＋ √3。` }, { t: `−6 + ${R(3)}`, why: '兩個根都是「2 加減 √3」，2 是正的。' }],
        explain: `<p>開根號：x − 2 ＝ ±${R(3)} → x ＝ 2 ± ${R(3)}。<br>a ＞ b，所以 a ＝ 2 ＋ ${R(3)}、b ＝ 2 − ${R(3)}。<br>2a + b ＝ 4 ＋ 2${R(3)} ＋ 2 − ${R(3)} ＝ 6 ＋ ${R(3)}。答案 (C)。</p>`,
        steps: [
          { q: `${M(sq('(x − 2)') + ' ＝ 3')}，所以 x − 2 ＝ ？`, options: [{ t: `${R(3)} 或 −${R(3)}`, ok: true, why: '3 不是完全平方數，就留根號。' }, { t: '3 或 −3', why: '平方是 3 的數是 ±√3。' }] },
          { q: 'a 是比較大的根。a、b 分別是？', options: [{ t: `a ＝ 2 + ${R(3)}，b ＝ 2 − ${R(3)}`, ok: true, why: '加 √3 的比較大。' }, { t: `a ＝ 2 − ${R(3)}，b ＝ 2 + ${R(3)}`, why: '√3 是正的，加上去才比較大。' }] },
          { q: `2a + b ＝ 2(2 + ${R(3)}) + (2 − ${R(3)}) ＝ ？`, options: [{ t: `6 + ${R(3)}`, ok: true, why: `4 ＋ 2 ＝ 6；2√3 − √3 ＝ √3。` }, { t: `6 + 3${R(3)}`, why: `b 裡面是「減」√3：2√3 − √3。` }, { t: '6', why: '2√3 − √3 還剩一個 √3。' }] }
        ] }
    ]);
  }

  K.run('4-2a', ['先猜猜看：平方與補一塊', '動手玩：補一角變正方形', '收成 4 句話', '會考題改寫版', '會考實戰：照原題做做看'], { guess, play, know, exam, real });
})();
