/* ===== 數學 3-3b 十字交乘（x² 係數不是 1） ===== */
(function () {
  'use strict';
  const U = Unit4, h = U.h, K = MK, M = K.M, X2 = K.X2;
  const P = (a, b, c) => M(K.poly(a, b, c));

  function guess(p, api) {
    U.guess(p, api, [
      { q: `${M('(2x + 1)(x + 3)')} 乘開，中間的 x 項是多少？`, options: [{ t: '7x', ok: true }, { t: '4x' }, { t: '5x' }],
        reveal: '2x × 3 ＝ 6x，1 × x ＝ x，加起來 <b>7x</b>。注意：不是 1 ＋ 3 ＝ 4，因為前面的 x 帶了係數 2。' },
      { q: `所以 ${P(2, 7, 3)} 要因式分解，還能只找「加起來是 7」的兩個數嗎？`, options: [{ t: '不行，要交叉相乘再加', ok: true }, { t: '可以，跟之前一樣' }],
        reveal: '<b>不行</b>。x² 前面有係數時，中間項是「<b>交叉相乘</b>再加起來」。畫十字就不會亂。' }
    ]);
  }

  function play(p, api) {
    let S;
    const card = h('<div class="card"></div>'); p.appendChild(card);
    const tk = U.tasks(p, api, [
      { text: `試試看：${P(2, 7, 3)}，右邊放哪一組才對？`, setup() { S.setTarget(2, 7, 3); }, check: () => S.hit(),
        qs: () => [{ q: '「1、3」對了。如果上下對調變成「3、1」，中間項會是多少？', hint: '2x × 1 ＋ x × 3。',
          options: [{ t: '5x，不對了', ok: true, why: '2x × 1 ＋ x × 3 ＝ 5x。同一組數字，<b>上下位置不同，結果就不同</b>。' }, { t: '還是 7x', why: '按按看「3、1」那顆按鈕。' }] }],
        found: '中間項 ＝ <b>交叉相乘再加</b>。同一組數字湊不到，就<b>上下對調</b>試試。' },
      { text: `換一題：${P(3, -10, 8)}。`, setup() { S.setTarget(3, -10, 8); }, check: () => S.hit(),
        qs: () => [{ q: '最後是 ＋8、中間是 −10x，右邊兩個數的符號是？', options: [{ t: '兩個都負', ok: true, why: '跟 3-3a 一樣：最後是正 → 同號；中間是負 → 都負。' }, { t: '一正一負', why: '一正一負乘起來是負的，可是最後是 ＋8。' }] }],
        found: '正負號的判斷跟之前一樣：<b>先看最後一項</b>。' },
      { text: `最後一題：${P(2, 1, -6)}。`, setup() { S.setTarget(2, 1, -6); }, check: () => S.hit(),
        qs: () => [{ q: '十字圖畫好了，答案要怎麼讀？', options: [{ t: '橫著讀：(2x − 3)(x + 2)', ok: true, why: '每一<b>橫列</b>是一個括號。乘開檢查：4x − 3x ＝ x ✔' }, { t: '斜著讀：(2x + 2)(x − 3)', why: '斜線只是用來「算中間項」的，答案要橫著讀。' }] }],
        found: '<b>斜著乘、橫著讀</b>。寫完一定乘開檢查中間項。' }
    ]);
    S = K.crossSim(card, () => tk.check());
    card.appendChild(tk.slot); p.insertBefore(p.querySelector('.u4-task'), card); tk.start();
  }

  function know(p, api) {
    p.appendChild(h('<p class="muted">把剛剛玩到的，收成 4 句話。</p>'));
    K.crossPic(U.card(p, '① 左邊拆 x² 項，右邊拆常數項', `<p>${P(2, 7, 3)}：左邊寫 2x、x（乘起來 2x²），右邊寫 1、3（乘起來 3）。</p><p><b>交叉相乘加起來</b> ＝ 中間項 7x 就對了。</p>`), 2, 1, 1, 3);
    K.table(U.card(p, '② 湊不到就換', '<p>照順序試，不要亂猜：</p>'), ['順序', '做什麼'], [['1', '右邊兩個數上下對調'], ['2', '換另一組乘起來一樣的數'], ['3', '左邊換拆法（例：6x² 可拆 6x、x 或 3x、2x）']], 360);
    K.crossPic(U.card(p, '③ 斜著乘、橫著讀', `<p>${P(3, -10, 8)} ＝ (3x − 4)(x − 2)</p><p>斜線是算中間項用的；每一<b>橫列</b>才是一個括號。</p>`), 3, -4, 1, -2);
    K.table(U.card(p, '④ 會考最愛這樣問', `<p>「${P(5, 17, -12)} 可分解成 (x + a)(bx + c)，求 a + c」</p><p>題目已經給了括號的樣子：x × bx ＝ 5x²，所以 <b>b ＝ 5</b>，只剩 a、c 要找。</p>`),
      ['先做', '再做'], [['對照 x² 項，知道 b', '找 a、c：乘起來是常數項，交叉相乘加起來是中間項']], 380);
    const c = h('<div class="card"><h3>✏️ 檢查一下</h3></div>'); p.appendChild(c);
    U.choice(c, { q: `${P(3, 5, 2)} 因式分解是哪一個？`, hint: '左邊 3x、x；右邊 1、2 或 2、1。交叉相乘加起來要 5x。',
      options: [{ t: '(3x + 2)(x + 1)', ok: true, why: '3x × 1 ＋ x × 2 ＝ 5x ✔' }, { t: '(3x + 1)(x + 2)', why: '3x × 2 ＋ x × 1 ＝ 7x，不是 5x。' }, { t: '(3x + 2)(x + 3)', why: '2 × 3 ＝ 6，常數項不對。' }], onDone() { api.done(); } });
  }

  function exam(p, api) {
    U.exam(p, api, {
      intro: '這兩題是照會考題的樣子改寫的，數字比較小。答錯可以再選。',
      benchLabel: '想畫十字？打開模擬（可練習 3x² + 10x − 8）',
      bench: host => { const s = K.crossSim(host, () => {}); s.setTarget(3, 10, -8); },
      qs: [
        { src: '改寫自 108 年會考第 8 題', q: `若多項式 ${P(3, 10, -8)} 可因式分解成 ${M('(x + a)(bx + c)')}，其中 a、b、c 均為整數，則 a + c 之值為何？`,
          hint: 'x × bx ＝ 3x²，所以 b ＝ 3。再找 a、c：a × c ＝ −8，交叉 c ＋ 3a ＝ 10。',
          options: [{ t: '2', ok: true, why: '(x + 4)(3x − 2)：−2x ＋ 12x ＝ 10x ✔。a ＝ 4、c ＝ −2，a + c ＝ 2。' }, { t: '6', why: 'c 是 −2 不是 2：4 × 2 ＝ ＋8，常數項會錯。' }, { t: '−2', why: '(x − 4)(3x + 2) 的中間項是 −10x，符號反了。' }, { t: '7', why: '7 是 a ＋ b；題目問 a ＋ c。' }] },
        { src: '改寫自 111 年會考第 8 題', q: `多項式 ${P(6, 1, -2)} 可因式分解成 ${M('(2x + a)(bx + c)')}，其中 a、b、c 均為整數，求 a + 2c 之值為何？`,
          hint: '2x × bx ＝ 6x²，所以 b ＝ 3。a × c ＝ −2，交叉 2c ＋ 3a ＝ 1。',
          options: [{ t: '−3', why: '(2x + 1)(3x − 2) 的中間項是 −x，符號反了。' }, { t: '1', why: '再算一次 a ＋ 2c：a ＝ −1、c ＝ 2。' }, { t: '3', ok: true, why: '(2x − 1)(3x + 2)：4x − 3x ＝ x ✔。a ＝ −1、c ＝ 2，a + 2c ＝ 3。' }, { t: '5', why: 'a 是 −1，不是 1。' }] }
      ]
    });
  }

  function real(p, api) {
    U.real(p, api, [
      { stars: 2, src: '108 年會考 第 8 題',
        q: `若多項式 ${P(5, 17, -12)} 可因式分解成 ${M('(x + a)(bx + c)')}，其中 a、b、c 均為整數，則 a + c 之值為何？`,
        options: [{ t: '1', ok: true, why: '(x + 4)(5x − 3)，a ＝ 4、c ＝ −3，a + c ＝ 1。' }, { t: '7', why: '4 ＋ 3 ＝ 7？c 是 −3：4 × 3 ＝ ＋12，常數項會錯。' }, { t: '11', why: '11 是「a ＝ 3、c ＝ −4」時的中間項係數，不是 17；而且題目問的是 a ＋ c。' }, { t: '13', why: '再檢查交叉相乘：c ＋ 5a 要等於 17。' }],
        explain: '<p>x × bx ＝ 5x² → b ＝ 5。<br>(x + a)(5x + c)：a × c ＝ −12，交叉相乘 c ＋ 5a ＝ 17。<br>試 a ＝ 4、c ＝ −3：−3 ＋ 20 ＝ 17 ✔。<br>5x² + 17x − 12 ＝ (x + 4)(5x − 3)，a + c ＝ 4 ＋ (−3) ＝ 1。答案 (A)。</p>',
        steps: [
          { num: true, q: `${M('(x + a)(bx + c)')} 乘開的 x² 項是 bx²，要等於 5x²。b ＝ ？`, pre: 'b ＝', answer: 5, why: '所以是 (x + a)(5x + c)。' },
          { q: 'a × c ＝ −12，而且交叉相乘 c ＋ 5a ＝ 17。哪一組對？', options: [{ t: 'a ＝ 4、c ＝ −3', ok: true, why: '4 × (−3) ＝ −12，−3 ＋ 5 × 4 ＝ 17 ✔' }, { t: 'a ＝ 3、c ＝ −4', why: '−4 ＋ 5 × 3 ＝ 11，不是 17。' }, { t: 'a ＝ −4、c ＝ 3', why: '3 ＋ 5 × (−4) ＝ −17，符號反了。' }] },
          { num: true, signed: true, q: 'a ＝ 4、c ＝ −3，a + c ＝ ？', pre: 'a + c ＝', answer: 1, diag: [{ v: 7, msg: 'c 是負的：4 ＋ (−3)。' }] }
        ] },
      { stars: 3, src: '105 年會考 第 6 題',
        q: `多項式 ${P(77, -13, -30)} 可因式分解成 ${M('(7x + a)(bx + c)')}，其中 a、b、c 均為整數，求 a + b + c 之值為何？`,
        options: [{ t: '0', why: '再檢查 b：7x × bx ＝ 77x²。' }, { t: '10', why: '如果 a ＝ 5、c ＝ −6：中間項是 −42x ＋ 55x ＝ ＋13x，符號反了。' }, { t: '12', ok: true, why: '(7x − 5)(11x + 6)，a ＝ −5、b ＝ 11、c ＝ 6，和是 12。' }, { t: '22', why: '5 ＋ 11 ＋ 6 ＝ 22？a 是 −5。' }],
        explain: '<p>7x × bx ＝ 77x² → b ＝ 11。<br>(7x + a)(11x + c)：a × c ＝ −30，交叉相乘 7c ＋ 11a ＝ −13。<br>30 ＝ 5 × 6，試 a ＝ −5、c ＝ 6：42 − 55 ＝ −13 ✔。<br>a + b + c ＝ −5 ＋ 11 ＋ 6 ＝ 12。答案 (C)。<br>💡 數字很大別怕：題目給了 7x，b 馬上知道，剩下只是試 30 的因數。</p>',
        steps: [
          { num: true, q: '7x × bx ＝ 77x²。b ＝ ？', pre: 'b ＝', answer: 11, why: '所以是 (7x + a)(11x + c)。' },
          { q: 'a × c ＝ −30，交叉相乘 7c ＋ 11a ＝ −13。哪一組對？', options: [{ t: 'a ＝ −5、c ＝ 6', ok: true, why: '7 × 6 ＋ 11 × (−5) ＝ 42 − 55 ＝ −13 ✔' }, { t: 'a ＝ 5、c ＝ −6', why: '−42 ＋ 55 ＝ ＋13，符號反了。' }, { t: 'a ＝ −6、c ＝ 5', why: '35 − 66 ＝ −31。' }] },
          { num: true, signed: true, q: 'a ＝ −5、b ＝ 11、c ＝ 6，a + b + c ＝ ？', pre: '＝', answer: 12, diag: [{ v: 22, msg: 'a 是 −5，不是 5。' }] }
        ] },
      { stars: 3, src: '111 年會考 第 8 題',
        q: `多項式 ${P(39, 5, -14)} 可因式分解成 ${M('(3x + a)(bx + c)')}，其中 a、b、c 均為整數，求 a + 2c 之值為何？`,
        options: [{ t: '−12', ok: true, why: '(3x + 2)(13x − 7)，a ＝ 2、c ＝ −7，a + 2c ＝ 2 − 14 ＝ −12。' }, { t: '−3', why: '如果 a ＝ −7、c ＝ 2：交叉是 6 − 91 ＝ −85，不是 5。' }, { t: '3', why: '如果 a ＝ 7、c ＝ −2：交叉是 −6 ＋ 91 ＝ 85，不是 5。' }, { t: '12', why: 'a ＝ −2、c ＝ 7 的中間項是 −5x，符號反了。' }],
        explain: '<p>3x × bx ＝ 39x² → b ＝ 13。<br>(3x + a)(13x + c)：a × c ＝ −14，交叉相乘 3c ＋ 13a ＝ 5。<br>14 ＝ 2 × 7，試 a ＝ 2、c ＝ −7：−21 ＋ 26 ＝ 5 ✔。<br>a + 2c ＝ 2 ＋ 2 × (−7) ＝ −12。答案 (A)。</p>',
        steps: [
          { num: true, q: '3x × bx ＝ 39x²。b ＝ ？', pre: 'b ＝', answer: 13, why: '所以是 (3x + a)(13x + c)。' },
          { q: 'a × c ＝ −14，交叉相乘 3c ＋ 13a ＝ 5。哪一組對？', options: [{ t: 'a ＝ 2、c ＝ −7', ok: true, why: '3 × (−7) ＋ 13 × 2 ＝ −21 ＋ 26 ＝ 5 ✔' }, { t: 'a ＝ −2、c ＝ 7', why: '21 − 26 ＝ −5，符號反了。' }, { t: 'a ＝ 7、c ＝ −2', why: '−6 ＋ 91 ＝ 85。' }] },
          { num: true, signed: true, q: 'a ＝ 2、c ＝ −7，a + 2c ＝ ？', pre: 'a + 2c ＝', answer: -12, diag: [{ v: 16, msg: 'c 是 −7：2 ＋ 2 × (−7)。' }, { v: -5, msg: '題目問 a ＋ 2c，c 要乘 2。' }] }
        ] }
    ]);
  }

  K.run('3-3b', ['先猜猜看：中間項怎麼來？', '動手玩：畫十字、試數字', '收成 4 句話', '會考題改寫版', '會考實戰：照原題做做看'], { guess, play, know, exam, real });
})();
