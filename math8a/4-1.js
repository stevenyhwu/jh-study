/* ===== 4-1 解一元二次方程式：可可貓的猜數字魔術（3 關） =====
   方程式＝猜祕密數字；乘起來是 0 → 至少一個是 0；用第三章的因式分解把它拆開 */
(function () {
  'use strict';
  const R = String.raw;
  const { areaBox, C } = Viz;
  const challenge = s => `<span class="chal">⭐ 挑戰題</span> ${s}`;
  const formula = (f, tip) => `<div class="formula">${f}</div>${tip ? `<div class="tip">${tip}</div>` : ''}`;
  const note = '<div class="muted small">（負的就按 ± 變成負數；兩個解的順序可以對調）</div>';
  // 兩個整數解
  const two = (q, a, b, hint, diag) => ({ type: 'num', q: q + note, groups: [[0], [1]],
    fields: [{ pre: R`\(x=\)`, answer: a, diag }, { pre: '　或　', answer: b, diag }], hint });
  // 兩個分數解 p/q
  const twoF = (q, a, b, c, d, hint) => ({ type: 'num', q: q + '<div class="muted small">（寫成分數「分子／分母」，整數的分母填 1；負號放在分子）</div>', groups: [[0, 1], [2, 3]],
    fields: [{ pre: R`\(x=\)`, answer: a }, { pre: '／', answer: b }, { nl: true, pre: R`或 \(x=\)`, answer: c }, { pre: '／', answer: d }], hint });
  const chips = (h, list) => { h.appendChild(Lesson.h(`<div class="chips">${list.map(s => `<span>${s}</span>`).join('')}</div>`)); JH.renderMath(h); };

  /* =========================================================
     第 1 關：猜祕密數字（一元二次方程式與它的解）
     ========================================================= */
  const S1 = { id: 's1', badge: '🎩', title: '第 1 關　猜祕密數字', steps: [
    { say: '可可貓想了一個<b>祕密數字</b>：「它自己乘自己，等於 9。」<br>用 \\(x\\) 代表祕密數字，寫成 \\(x^2=9\\)。',
      ask: { type: 'choice', q: '祕密數字可能是多少？', options: [
        { t: R`3 或 −3`, ok: true, why: R`\(3\times3=9\)，\((-3)\times(-3)=9\)，兩個都對！（2-1 學過，9 的平方根是 ±3）` },
        { t: '只有 3', why: '負負得正，(−3)×(−3) 也是 9 喔！' },
        { t: '4.5', why: '4.5×4.5＝20.25，不是 9。' }] },
      after: '像 \\(x^2=9\\) 這種，只有一個未知數（一元）、最高是平方（二次）的等式，叫做<b>一元二次方程式</b>。讓等式成立的數，叫做它的<b>解</b>（或<b>根</b>）。' },
    { say: '分辨看看：哪一個<b>不是</b>一元二次方程式？',
      ask: { type: 'choice', options: [
        { t: R`\(x^2+3x=x^2-1\)`, ok: true, why: R`兩邊的 \(x^2\) 會消掉，變成 \(3x=-1\)，只剩一次，是一元<b>一</b>次方程式。<b>要先整理再判斷</b>！` },
        { t: R`\(x^2-5x+6=0\)`, why: '最高是 x²，只有 x 一個未知數，是一元二次方程式。' },
        { t: R`\(x(x+5)=7\)`, why: R`乘開是 \(x^2+5x=7\)，是一元二次方程式。` },
        { t: R`\(2x^2=8\)`, why: '它是一元二次方程式。' }] } },
    { say: R`怎麼知道一個數是不是解？<b>代進去算算看</b>！<br>\(x=2\) 是 \(x^2-3x+2=0\) 的解嗎？`,
      ask: { type: 'num', q: R`把 \(x=2\) 代入左邊：\(2^2-3\times2+2=\)？`, fields: [{ answer: 0 }] },
      after: '等於右邊的 0 ✔，所以 x＝2 是解。' },
    { say: R`\(x^2-2x-3=0\)：代 \(x=-1\) 和 \(x=1\) 試試。`,
      ask: { type: 'num', fields: [{ pre: R`\(x=-1\)：\(1+2-3=\)`, answer: 0 }, { pre: R`　\(x=1\)：\(1-2-3=\)`, answer: -4 }] },
      after: '所以 x＝−1 是解，x＝1 <b>不是</b>解（−4 ≠ 0）。' },
    { say: challenge(R`已知 \(x=2\) 是 \(x(x-k)=6\) 的一個解。`),
      ask: { type: 'num', q: R`代入：\(2(2-k)=6\)，所以 \(k=\)？`, fields: [{ answer: -1, diag: [{ v: 1, msg: '2−k＝3，所以 k＝2−3＝−1。' }] }], hint: '2−k＝3' } }
  ] };

  /* =========================================================
     第 2 關：乘起來是 0
     ========================================================= */
  const S2 = { id: 's2', badge: '0️⃣', title: '第 2 關　乘起來是 0', steps: [
    { say: '可可貓的新謎題：「兩個數相乘等於 <b>0</b>。」',
      ask: { type: 'choice', q: R`如果 \(A\times B=0\)，你能確定什麼？`, options: [
        { t: R`\(A\) 和 \(B\) 至少有一個是 0`, ok: true, why: '對！不是 0 的數互相乘，永遠不會變成 0。' },
        { t: '兩個都一定是 0', why: '3×0 也是 0 喔，只要<b>其中一個</b>是 0 就夠了。' },
        { t: '什麼都不能確定', why: '試試看：兩個都不是 0 的數相乘，會等於 0 嗎？' }] },
      after: formula(R`\(A\times B=0\;\Rightarrow\;A=0\;\text{或}\;B=0\)`, '這就是解一元二次方程式的祕密武器！') },
    { say: R`\((x-3)(x+5)=0\)：兩個括號相乘是 0，所以……`,
      scene: (h) => { chips(h, [R`\(x-3=0\)`, '或', R`\(x+5=0\)`]); },
      ask: two(R`\((x-3)(x+5)=0\)`, 3, -5, 'x−3＝0 → x＝3；x＋5＝0 → x＝−5', [{ v: -3, msg: 'x−3＝0，x 要是 +3 才會讓它變 0。' }, { v: 5, msg: 'x＋5＝0，x 要是 −5。' }]) },
    { say: '再一題：',
      ask: two(R`\((x+1)(x-7)=0\)`, -1, 7) },
    { say: R`有係數的：\((2x-3)(3x+1)=0\)<br>\(2x-3=0\Rightarrow x=\frac32\)；\(3x+1=0\Rightarrow x=?\)`,
      ask: twoF('兩個解：', 3, 2, -1, 3, '3x＝−1，x＝−1/3') },
    { say: R`⚠️ \(x(x+4)=0\)，小明說：「答案是 \(x=-4\)。」`,
      ask: { type: 'choice', q: '小明漏掉什麼？', options: [
        { t: R`漏了 \(x=0\)！前面那個 \(x\) 也是一個「括號」`, ok: true, why: R`\(x\times(x+4)=0\)，\(x=0\) 或 \(x+4=0\)。兩個解都要寫。` },
        { t: '沒有漏', why: 'x＝0 代進去：0×4＝0，也成立喔！' }] } }
  ] };

  /* =========================================================
     第 3 關：先拆開再解（因式分解法）
     ========================================================= */
  const S3 = { id: 's3', badge: '🧩', title: '第 3 關　先拆開再解', steps: [
    { say: R`第三章的因式分解派上用場了！<br>\(x^2-5x=0\)：先提公因式 \(x\)。`,
      ask: two(R`\(x(x-5)=0\)`, 0, 5) ,
      after: R`⚠️ 不可以兩邊同除以 \(x\)！那樣會把 \(x=0\) 這個解弄丟。` },
    { say: R`\(x^2-9=0\)：用平方差 \((x+3)(x-3)=0\)。`,
      ask: two(R`\(x^2-9=0\)`, 3, -3),
      after: R`也可以直接想：\(x^2=9\)，\(x=\pm3\)（平方根法）。` },
    { say: R`\(x^2+6x+9=0\)：它是完全平方 \((x+3)^2=0\)。`,
      ask: { type: 'num', q: R`\((x+3)(x+3)=0\)，\(x=\)？`, fields: [{ answer: -3 }] },
      after: R`兩個括號一樣，兩個解也一樣，叫做<b>重根</b>：\(x=-3\)（重根）。` },
    { say: R`十字交乘：\(x^2-x-12=0\)，乘起來 −12、加起來 −1。`,
      ask: two(R`\((x-4)(x+3)=0\)`, 4, -3) },
    { say: R`⚠️ 小華解 \(x^2=2x+8\)，寫成 \(x(x-2)=8\)，然後說「\(x=8\) 或 \(x-2=8\)」。`,
      ask: { type: 'choice', q: '小華錯在哪裡？', options: [
        { t: '乘起來是 8，不能拆！一定要先移項，讓一邊是 0', ok: true, why: R`2×4＝8、1×8＝8……乘起來是 8 有好多種可能。只有「乘起來是 <b>0</b>」才能拆。` },
        { t: '沒有錯', why: R`代 \(x=8\) 檢查：\(64=16+8\)？不成立喔！` }] } },
    { say: R`先移項：\(x^2-2x-8=0\)，再分解：`,
      ask: two(R`\(x^2-2x-8=0\)`, 4, -2, '乘起來 −8、加起來 −2：−4 和 2 → (x−4)(x+2)') ,
      after: '👉 <b>解題步驟：① 移項讓右邊是 0 ② 因式分解 ③ 每個括號 ＝ 0</b>' },
    { say: R`\(2x^2+x-3=0\)：十字交乘 \((2x+3)(x-1)=0\)。`,
      ask: twoF('兩個解：', 1, 1, -3, 2, '2x＋3＝0 → x＝−3/2；x−1＝0 → x＝1') },
    { say: challenge(R`\((x+1)^2=16\)：括號整包開根號！`),
      ask: two(R`\(x+1=\pm4\)，所以`, 3, -5, 'x＋1＝4 或 x＋1＝−4') },
    { say: challenge(R`方程式 \(x^2-x-6=0\) 和 \(x^2+x-a=0\) 有一個共同的解。<br>先解第一個：\((x-3)(x+2)=0\)，\(x=3\) 或 \(-2\)。`),
      ask: { type: 'choice', q: R`把共同解代進第二個式子，\(a\) 可能是多少？`, options: [
        { t: '12 或 2', ok: true, why: R`代 \(x=3\)：\(9+3-a=0\)，\(a=12\)；代 \(x=-2\)：\(4-2-a=0\)，\(a=2\)。` },
        { t: '只有 12', why: '共同解也可能是 −2 喔，兩個都要試。' },
        { t: '6', why: '把 x＝3 或 x＝−2 代進 x²＋x−a＝0 算算看。' }] } }
  ] };

  /* =========================================================
     第 4 關：解方程式的變化題
     ========================================================= */
  const S4 = { id: 's4', badge: '🔄', title: '第 4 關　變化題', steps: [
    { say: R`\((x+3)(x-2)=6\)：右邊不是 0，<b>不能拆</b>！先乘開、移項：`,
      ask: { type: 'num', q: R`乘開移項：\(x^2+x-6-6=0\)，也就是 \(x^2+x-12=0\)。解出：` + note, groups: [[0], [1]], fields: [{ pre: R`\(x=\)`, answer: 3 }, { pre: '　或　', answer: -4 }], hint: '(x+4)(x−3)＝0' } },
    { say: R`⚠️ \(2x(x-3)=5(x-3)\)。小明把兩邊同除以 \((x-3)\)，得到 \(2x=5\)，\(x=\frac52\)。`,
      ask: { type: 'choice', q: '小明漏掉什麼？', options: [
        { t: R`漏了 \(x=3\)！代 3 進去兩邊都是 0`, ok: true, why: R`除以 \((x-3)\) 時，如果 \(x-3=0\) 就不能除。正確做法：移項提公因式 \((x-3)(2x-5)=0\)。` },
        { t: '沒有漏', why: R`代 \(x=3\) 試試：左邊 \(2\times3\times0=0\)，右邊 \(5\times0=0\)，也成立喔！` }] },
      after: '👉 <b>兩邊有同一包，不能約掉！要移到同一邊，再提出來。</b>' },
    { say: '寫出兩個解：',
      ask: twoF(R`\((x-3)(2x-5)=0\)`, 3, 1, 5, 2, 'x−3＝0 → x＝3（分母填 1）；2x−5＝0 → x＝5/2') },
    { say: R`<b>反過來</b>：方程式 \(x^2+mx+n=0\) 的兩個解是 3 和 −5，求 m、n。<br>有這兩個解，方程式就是 \((x-3)(x+5)=0\)！`,
      ask: { type: 'num', q: R`\((x-3)(x+5)=x^2+mx+n\)` + note.replace('兩個解的順序可以對調', '乘開比較'), fields: [{ pre: R`\(m=\)`, answer: 2 }, { pre: R`　\(n=\)`, answer: -15 }], hint: 'x²＋5x−3x−15' } },
    { say: R`<b>整包代入</b>：\(k\) 是 \(x^2+x-1=0\) 的一個解，所以 \(k^2+k-1=0\)，也就是 \(k^2+k=1\)。`,
      ask: { type: 'num', q: R`\(2k^2+2k+5=2(k^2+k)+5=\)？`, fields: [{ answer: 7 }] },
      after: '不用把 k 算出來，把 k²+k 整包換成 1 就好！' },
    { say: R`把 \((x-1)\) 當一包 🎁：\((x-1)^2-3(x-1)-10=0\) → 🎁²−3🎁−10＝(🎁−5)(🎁+2)＝0`,
      ask: { type: 'num', q: '🎁＝5 或 −2，也就是 x−1＝5 或 x−1＝−2：' + note, groups: [[0], [1]], fields: [{ pre: R`\(x=\)`, answer: 6 }, { pre: '　或　', answer: -1 }] } },
    { say: challenge(R`\(x\)、\(y\) 都不是 0，而且 \(2x^2+xy-y^2=0\)。十字交乘：\((2x-y)(x+y)=0\)。`),
      ask: { type: 'num', q: R`\(\frac yx\) 可能是？` + note, groups: [[0], [1]], fields: [{ answer: 2 }, { pre: '或', answer: -1 }], hint: '2x−y＝0 → y＝2x；x＋y＝0 → y＝−x' } }
  ] };

  const STAGES = [S1, S2, S3, S4];
  document.addEventListener('DOMContentLoaded', () => Lesson.mount('math8a-4-1', STAGES, { signed: true }));
})();
